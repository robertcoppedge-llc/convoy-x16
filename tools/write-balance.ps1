# Writes src/balance.h (or balance.header) from x16project.json.
# Project-X16 writes the same header on Save and before Build & Run.
# A command-line build runs this so the two stay on the same numbers.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$proj = Get-Content -Raw (Join-Path $root 'x16project.json') | ConvertFrom-Json
$b = $proj.balance
if (-not $b -or -not $b.units) { exit 0 }
$names = @{}
if ($b.groups) { foreach ($g in $b.groups) { $names[$g.id] = $g.name } }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by Project-X16 from x16project.json balance. The game includes this before its own defaults. */')
[void]$sb.AppendLine('#ifndef X16_BALANCE_H')
[void]$sb.AppendLine('#define X16_BALANCE_H')
$last = $null
foreach ($u in $b.units) {
    $heading = $null
    if ($u.group) {
        if ($names.ContainsKey([string]$u.group) -and $names[[string]$u.group]) { $heading = $names[[string]$u.group] }
        else { $heading = [string]$u.group }
    }
    if ($heading -and $heading -ne $last) {
        $last = $heading
        [void]$sb.AppendLine("/* $heading */")
    }
    foreach ($f in $u.fields) {
        if (-not $f.symbol) { continue }
        $comment = [string]$f.detail
        if ($f.pending) { $comment = ("$comment The game does not read this yet.").Trim() }
        if ($comment) { [void]$sb.AppendLine("/* $($comment.Replace('*/','')) */") }
        [void]$sb.AppendLine("#define $($f.symbol) $($f.value)")
    }
}
[void]$sb.AppendLine('#endif')
$rel = if ($b.header) { [string]$b.header } else { 'src/balance.h' }
$path = Join-Path $root ($rel -replace '/', '\')
$dir = Split-Path -Parent $path
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
$text = $sb.ToString().Replace("`n", "`r`n").Replace("`r`r`n", "`r`n")
[System.IO.File]::WriteAllText($path, $text)
